/* ===== Ссылки на оплату ===========================================
   Пока строка пустая, кнопка «Купить» ведёт на форму обратной связи
   и подставляет название продукта в сообщение — заявка приходит на
   почту. Когда подключите эквайринг, впишите сюда адреса страниц
   оплаты, и кнопки начнут вести прямо туда.
   ================================================================= */
var PAYMENT_LINKS = {
  spiktera:    '',   // Курс «Спиктера» — 15 000 ₽ на пресейле, старт в октябре 2026
  constructor: ''    // Конструктор туристических проектов — оплаты картой не будет
};
/* Строку constructor НЕ удаляйте, даже если она всегда пустая: `constructor` —
   служебное имя в JavaScript, и без своего ключа объект отдаёт унаследованное
   значение вместо пустой строки. Кнопка тогда ведёт в никуда.

   Конструктор туристических проектов продаётся по счёту юридическим лицам:
   кнопка «Заказать» ведёт на форму, заявка приходит на почту, счёт
   Александра выставляет лично. Ссылку на оплату сюда вписывать не нужно.

   Калькулятор силы бренда бесплатный и открывается прямо на
   /products/brand-calculator, кнопки покупки у него нет. */

(function () {
  'use strict';

  // Название продукта подставляется в письмо, чтобы сразу было понятно,
  // о чём заявка.
  var TITLES = {
    spiktera:    'Курс «Спиктера»',
    constructor: 'Конструктор туристических проектов'
  };

  function apply() {
    [].forEach.call(document.querySelectorAll('[data-buy]'), function (a) {
      var key = a.getAttribute('data-buy');
      // hasOwnProperty, а не PAYMENT_LINKS[key]: у ключа `constructor` иначе
      // подхватывается унаследованное значение из прототипа
      var paid = Object.prototype.hasOwnProperty.call(PAYMENT_LINKS, key)
        ? PAYMENT_LINKS[key] : '';

      if (paid) {
        a.href = paid;
        a.target = '_blank';
        a.rel = 'noopener noreferrer';
        return;
      }
      // Запасной путь: форма на главной с подставленным продуктом
      a.href = '/?product=' + encodeURIComponent(TITLES[key] || key) + '#contact';
      a.removeAttribute('target');
    });
  }

  document.addEventListener('DOMContentLoaded', function () {
    apply();
    if (window.MOTION) MOTION.reveal();
  });
})();
